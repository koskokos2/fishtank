// Preserve all three generated depth plates and their native alpha. The
// backdrop renderer applies a restrained monochrome palette at load time.
import { readFileSync, writeFileSync } from "node:fs";

const sources = {
  far: "art/sunken-city-far-v2.png",
  middle: "art/sunken-city-middle-v2.png",
  near: "art/sunken-city-near-v2.png",
};

writeFileSync("src/sunkenRuinsImage.ts",
  `// GENERATED by tools/embed-sunken-ruins.ts; source paths are listed in that tool.\n` +
  Object.entries(sources).map(([depth, path]) => {
    const source = readFileSync(path);
    return `export const SUNKEN_CITY_${depth.toUpperCase()} = "data:image/png;base64,${source.toString("base64")}";\n`;
  }).join(""));
