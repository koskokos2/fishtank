// Pack six generated finger-walking poses at one shared scale, with a stable
// wrist x anchor and a common planted-fingertip line. Frame 1 is also the idle.
import { readFileSync, writeFileSync } from "node:fs";
import { decodePng, encodePng } from "./png";

const SRC = "art/crawling-hand-atlas-transparent.png";
const OUT = "art/crawling-hand-atlas-128.png";
const OUT_TS = "src/crawlingHandAtlas.ts";
const OUT_META = "art/crawling-hand-atlas-128.json";
const FRAMES = 6;
const TILE = 128;
const PANEL = 512;
const GROUND_LINE = 118;
const ALPHA_MIN = 32;
type Buf = { data: Uint8Array; w: number; h: number };
const src = decodePng(readFileSync(SRC));
if (src.w !== 1536 || src.h !== 1024)
  throw new Error(`expected 1536x1024 source, got ${src.w}x${src.h}`);

const poses = Array.from({ length: FRAMES }, (_, frame) => {
  const ox = (frame % 3) * PANEL;
  const oy = Math.floor(frame / 3) * PANEL;
  let left = PANEL, top = PANEL, right = -1, bottom = -1;
  for (let y = 0; y < PANEL; y++) for (let x = 0; x < PANEL; x++) {
    if (src.rgba[((oy + y) * src.w + ox + x) * 4 + 3] < ALPHA_MIN) continue;
    left = Math.min(left, x); right = Math.max(right, x);
    top = Math.min(top, y); bottom = Math.max(bottom, y);
  }
  if (right < left || left < 4 || right >= PANEL - 4 || top < 4 || bottom >= PANEL - 4)
    throw new Error(`empty or clipped source pose ${frame}`);
  // The uppermost opaque band is the closed wrist cap in every pose. Unlike a
  // silhouette center, it does not move sideways when a finger reaches forward.
  let weightedX = 0, weight = 0;
  for (let y = top; y < top + 24; y++) for (let x = left; x <= right; x++) {
    const a = src.rgba[((oy + y) * src.w + ox + x) * 4 + 3];
    if (a < 128) continue;
    weightedX += x * a; weight += a;
  }
  if (!weight) throw new Error(`missing wrist cap in pose ${frame}`);
  const wristX = weightedX / weight;
  const w = right - left + 1, h = bottom - top + 1;
  const data = new Uint8Array(w * h * 4);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const si = ((oy + top + y) * src.w + ox + left + x) * 4;
    if (src.rgba[si + 3] < ALPHA_MIN) continue;
    data.set(src.rgba.subarray(si, si + 4), (y * w + x) * 4);
  }
  return { data, w, h, wristX: wristX - left, left, top, frame };
});

// A shared scale preserves hand identity instead of stretching each pose to fit.
const leftReach = Math.max(...poses.map(p => p.wristX));
const rightReach = Math.max(...poses.map(p => p.w - p.wristX));
const scale = Math.min(112 / (leftReach + rightReach), 84 / Math.max(...poses.map(p => p.h)));
const wristAnchorX = Math.round((TILE - (leftReach + rightReach) * scale) / 2 + leftReach * scale);
const sheet = new Uint8Array(TILE * FRAMES * TILE * 4);
const frames = poses.map(pose => {
  const image = resize(pose, Math.round(pose.w * scale), Math.round(pose.h * scale));
  const x0 = Math.round(wristAnchorX - pose.wristX * scale);
  const y0 = GROUND_LINE - image.h + 1;
  if (x0 < 4 || x0 + image.w > TILE - 4 || y0 < 4)
    throw new Error(`pose ${pose.frame} exceeds padded cell`);
  for (let y = 0; y < image.h; y++) for (let x = 0; x < image.w; x++) {
    const si = (y * image.w + x) * 4;
    const di = ((y0 + y) * TILE * FRAMES + pose.frame * TILE + x0 + x) * 4;
    if (image.data[si + 3]) sheet.set(image.data.subarray(si, si + 4), di);
  }
  return { frame: pose.frame, sourceBounds: { x: pose.left, y: pose.top, width: pose.w, height: pose.h },
    draw: { x: x0, y: y0, width: image.w, height: image.h }, wristX: wristAnchorX };
});
const png = encodePng(sheet, TILE * FRAMES, TILE);
writeFileSync(OUT, png);
writeFileSync(OUT_META, JSON.stringify({ name: "crawling-hand", source: SRC,
  layout: { columns: FRAMES, rows: 1, tile: TILE },
  animation: { walk: { from: 0, to: 5, loop: true }, idle: 1 },
  groundLine: GROUND_LINE, scale, frames }, null, 2) + "\n");
writeFileSync(OUT_TS,
  `// GENERATED by tools/gen-crawling-hand-atlas.ts — do not edit by hand.\n` +
  `export const CRAWLING_HAND_ATLAS = "data:image/png;base64,${png.toString("base64")}";\n` +
  `export const CRAWLING_HAND_FRAMES = ${FRAMES};\n` +
  `export const CRAWLING_HAND_TILE = ${TILE};\n` +
  `export const CRAWLING_HAND_GROUND_OFFSET = ${GROUND_LINE - TILE / 2};\n`);
console.log(`wrote ${OUT}, ${OUT_META}, and ${OUT_TS}`);
// Premultiplied-alpha area sampling keeps the generated pixel clusters crisp at
// the smaller runtime size without pulling dark colour through transparent edges.
function resize(input: Buf, outW: number, outH: number): Buf {
  const data = new Uint8Array(outW * outH * 4);
  const scaleX = input.w / outW;
  const scaleY = input.h / outH;
  for (let dy = 0; dy < outH; dy++) {
    const sy0 = dy * scaleY;
    const sy1 = (dy + 1) * scaleY;
    for (let dx = 0; dx < outW; dx++) {
      const sx0 = dx * scaleX;
      const sx1 = (dx + 1) * scaleX;
      let areaSum = 0;
      let alphaSum = 0;
      let red = 0;
      let green = 0;
      let blue = 0;
      for (let sy = Math.floor(sy0); sy < Math.ceil(sy1); sy++) {
        const wy = Math.max(0, Math.min(sy1, sy + 1) - Math.max(sy0, sy));
        for (let sx = Math.floor(sx0); sx < Math.ceil(sx1); sx++) {
          const wx = Math.max(0, Math.min(sx1, sx + 1) - Math.max(sx0, sx));
          const area = wx * wy;
          if (!area) continue;
          const si = (sy * input.w + sx) * 4;
          const alpha = input.data[si + 3] / 255;
          areaSum += area;
          alphaSum += alpha * area;
          red += input.data[si] * alpha * area;
          green += input.data[si + 1] * alpha * area;
          blue += input.data[si + 2] * alpha * area;
        }
      }
      if (!alphaSum) continue;
      const di = (dy * outW + dx) * 4;
      data[di] = Math.round(red / alphaSum);
      data[di + 1] = Math.round(green / alphaSum);
      data[di + 2] = Math.round(blue / alphaSum);
      data[di + 3] = Math.round((alphaSum / areaSum) * 255);
    }
  }
  return { data, w: outW, h: outH };
}

