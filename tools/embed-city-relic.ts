import { readFileSync, writeFileSync } from "node:fs";
import { PNG } from "pngjs";

// Source art stays lossless. Normalize each architectural fragment at
// its maximum display size (RES=6), preserving openings and native alpha.
const layers = [
  { name: "guardian", designWidth: 205, source: "art/sunken-city-landmark-guardian.png" },
  { name: "halloween", designWidth: 205, source: "art/halloween-city-mourner.png" },
] as const;
const sprites = layers.map(({ name, designWidth, source }) => {
  const png = PNG.sync.read(readFileSync(source));
  let left = png.width, top = png.height, right = 0, bottom = 0;
  for (let y = 0; y < png.height; y++) for (let x = 0; x < png.width; x++) {
    if (!png.data[(y * png.width + x) * 4 + 3]) continue;
    left = Math.min(left, x); right = Math.max(right, x);
    top = Math.min(top, y); bottom = Math.max(bottom, y);
  }
  if (left > right) throw new Error(`Empty ${name} landmark artwork`);
  const crop = { x: left, y: top, width: right - left + 1, height: bottom - top + 1 };
  const runtime = new PNG({ width: designWidth * 6, height: Math.round(designWidth * 6 * crop.height / crop.width) });
  for (let y = 0; y < runtime.height; y++) for (let x = 0; x < runtime.width; x++) {
    const sx = crop.x + Math.min(crop.width - 1, Math.floor((x + .5) * crop.width / runtime.width));
    const sy = crop.y + Math.min(crop.height - 1, Math.floor((y + .5) * crop.height / runtime.height));
    const from = (sy * png.width + sx) * 4;
    runtime.data.set(png.data.subarray(from, from + 4), (y * runtime.width + x) * 4);
  }
  const encoded = PNG.sync.write(runtime);
  writeFileSync(`art/sunken-city-landmark-${name}-runtime.png`, encoded);
  console.log(name, runtime.width, runtime.height);
  return { name, designWidth, width: runtime.width, height: runtime.height,
    image: `data:image/png;base64,${encoded.toString("base64")}` };
});
writeFileSync("src/cityRelicImage.ts", `// GENERATED by tools/embed-city-relic.ts; guardian head source for placement variants.\n`
  + `export const CITY_LANDMARK_IMAGES = ${JSON.stringify(sprites)} as const;\n`);
